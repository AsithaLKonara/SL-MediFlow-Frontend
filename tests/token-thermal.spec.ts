import { test, expect } from '@playwright/test';

test.describe('80mm Thermal Token Receipt Specification', () => {
  test('Token receipt must strictly fit within 80mm roll width and correctly partition multi-department tokens', async ({ page }) => {
    // Navigate to the token preview page
    await page.goto('http://localhost:3000/token-preview', { waitUntil: 'domcontentloaded' });

    const receiptRoot = page.locator('#thermal-token-receipt-root');
    await expect(receiptRoot).toBeVisible();

    // 1. Strict Physical Geometry:
    // 80mm thermal roll printable width is ~72mm (approx 270-290px at 96 DPI).
    // Bounding width must be <= 300px.
    const box = await receiptRoot.boundingBox();
    expect(box).not.toBeNull();
    expect(box!.width).toBeLessThanOrEqual(300);

    // 2. Official Logo & Doctor Consultation Token Assertions
    const logo = receiptRoot.locator('img[alt="AMAZ Hospital Logo"]').first();
    await expect(logo).toBeVisible();
    await expect(receiptRoot).toContainText('Doctor Consultation Token');
    await expect(receiptRoot.locator('h2').first()).toHaveText('05');
    await expect(receiptRoot).toContainText('ROOM 2');
    await expect(receiptRoot).toContainText('Dr. V.K.P.A. Mahesh Lakshman');
    await expect(receiptRoot).toContainText('Kamal Wickramasinghe (42y)');

    // 3. Laboratory Queue Token Assertions
    await expect(receiptRoot).toContainText('Laboratory Queue Token');
    await expect(receiptRoot.locator('h2').nth(1)).toHaveText('LA-01');
    await expect(receiptRoot).toContainText('LAB A');
    await expect(receiptRoot).toContainText('Full Blood Count (FBC)');

    // 4. Barcode and Instructions
    await expect(receiptRoot).toContainText('AMAZ-20261107-0012');
    await expect(receiptRoot).toContainText('Please wait for your number');
    await expect(receiptRoot).toContainText('Generated by AMAZ System');

    // 5. Emulate print media & PDF rendering at 80mm roll width
    await page.emulateMedia({ media: 'print' });
    await expect(receiptRoot).toBeVisible();

    const pdfBuffer = await page.pdf({
      width: '80mm',
      height: '200mm',
      printBackground: true,
      margin: {
        top: '2mm',
        right: '2mm',
        bottom: '4mm',
        left: '2mm'
      }
    });

    expect(pdfBuffer.length).toBeGreaterThan(1000);
  });
});

